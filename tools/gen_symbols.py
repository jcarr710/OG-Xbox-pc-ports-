"""Turn XbSymbolDatabase's scan of a default.xbe into a title symbol table.

    XbSymbolDatabaseCLI default.xbe > symbols.txt
    python3 tools/gen_symbols.py symbols.txt > titles/<name>/symbols.inc

XbSymbolDatabase (https://github.com/Cxbx-Reloaded/XbSymbolDatabase, MIT)
finds the XDK library functions and data that are statically linked into an
XBE. The output is only names and addresses; no game code is copied."""
import sys

seen = {}
for line in open(sys.argv[1], encoding='utf-8', errors='replace'):
    if ' = 0x' not in line:
        continue
    name, addr = line.strip().split(' = ')
    seen.setdefault(name, int(addr, 16))
print('/* Generated by tools/gen_symbols.py from an XbSymbolDatabase scan. */')
for name in sorted(seen):
    print('    { "%s", 0x%08x },' % (name, seen[name]))
